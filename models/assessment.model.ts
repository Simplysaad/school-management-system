import { Schema, model, models, Document, Types } from "mongoose";

export interface IQuizOption {
  _id?: Types.ObjectId;
  text: string;
  isCorrect: boolean;
}

export interface IQuestion {
  _id: Types.ObjectId; // Auto-generated by Mongoose subdocument schema
  title: string;
  description: string;
  type: "multiple-choice" | "true-false" | "short-answer" | "essay";
  options?: IQuizOption[];
  points: number;
}

export interface IAssessment extends Document {
  schoolId: Types.ObjectId;
  academicYear: string;
  term: string;
  classId: Types.ObjectId;
  subjectName: string;
  title: string;
  type: "PHYSICAL" | "ONLINE_QUIZ";
  maxScore: number;
  weightage: number;
  questions: Types.DocumentArray<IQuestion>;
  createdAt: Date;
  updatedAt: Date;
}

const QuizOptionSchema = new Schema<IQuizOption>({
  text: { type: String, required: true },
  isCorrect: { type: Boolean, required: true, default: false },
});

// Subdocument schema automatically assigns a unique `_id` to each question
const QuestionSchema = new Schema<IQuestion>({
  title: { type: String, required: true, trim: true },
  description: { type: String, required: true },
  type: {
    type: String,
    enum: ["multiple-choice", "true-false", "short-answer", "essay"],
    required: true,
  },
  options: [QuizOptionSchema],
  points: { type: Number, required: true, default: 1, min: 0 },
});

const AssessmentSchema = new Schema<IAssessment>(
  {
    schoolId: {
      type: Schema.Types.ObjectId,
      ref: "School",
      required: true,
      index: true,
    },
    academicYear: { type: String, required: true },
    term: { type: String, required: true },
    classId: {
      type: Schema.Types.ObjectId,
      ref: "Classroom",
      required: true,
      index: true,
    },
    subjectName: { type: String, required: true, trim: true },
    title: { type: String, required: true, trim: true },
    type: {
      type: String,
      enum: ["PHYSICAL", "ONLINE_QUIZ"],
      required: true,
      default: "PHYSICAL",
    },
    questions: [QuestionSchema],
    maxScore: { type: Number, required: true, default: 100 },
    weightage: { type: Number, required: true, default: 100 },
  },
  { timestamps: true }
);

export const Assessment =
  models.Assessment || model<IAssessment>("Assessment", AssessmentSchema);